# -*- coding: utf-8 -*-
"""
svg_to_scad_converter.py
------------------------

A Python-based converter that transforms halftone SVG files
into OpenSCAD 3D relief models (.scad).

Designed for artistic and precision workflows where circle-based halftone
patterns are converted into physical depth using a perceptual height model.

Author: Avtomat Agentics (based on DE Hammer original idea)
Version: 1.0
Python 3.8+
"""

## =====================================================
## SVG TO SCAD HALFTONE CONVERTER (Professional Edition)
## -----------------------------------------------------
## This script scans the SVG directory for halftone SVGs
## generated by the main GUI tool, and converts each
## unprocessed file into a 3D OpenSCAD relief.
##
## The height of each cylinder (dot) is computed using
## a perceptual gamma curve to simulate human contrast
## perception, achieving an artist-grade result.
##
## Each processed SVG is renamed with "_converted" to
## prevent reprocessing. Generated .scad files are
## stored in the SCAD folder for OpenSCAD rendering.
## =====================================================

from pathlib import Path
import xml.etree.ElementTree as ET
import os

## ==========================================
## DYNAMIC PATH CONFIGURATION (cross-folder)
## ==========================================

# Base directory of the script (runs from any location)
BASE_DIR = Path(__file__).resolve().parent

# Define folders relative to base directory
SVG_DIR = BASE_DIR / "SVG"
SCAD_DIR = BASE_DIR / "SCAD"

# Ensure folders exist
os.makedirs(SVG_DIR, exist_ok=True)
os.makedirs(SCAD_DIR, exist_ok=True)

## ==========================================
## GLOBAL CONVERSION PARAMETERS
## ==========================================

H_BASE = 0.5      # Base plate height in mm (physical support)
H_MAX = 2.0       # Maximum relief height in mm
GAMMA = 0.9       # Perceptual gamma for tone scaling (0.7–1.3 typical)
EXTRUDE_BASE = True  # Adds a flat base under the pattern for printability

## ==========================================
## HELPER / CORE CONVERSION LOGIC
## ==========================================

def convert_svg_to_scad(svg_file: Path):
    """
    Converts a halftone SVG file (either <circle> or Cairo-style <path>)
    into an OpenSCAD 3D relief (.scad). Each element becomes a cylinder
    whose height is proportional to its radius.
    """
    print(f"\nProcessing SVG file: {svg_file.name}")

    # Parse XML structure safely
    try:
        tree = ET.parse(svg_file)
        root = tree.getroot()
    except Exception as e:
        print(f"  Failed to parse {svg_file.name}: {e}")
        return

    circles = []

    # --- 1 Standard <circle> elements ---
    for element in root.iter():
        if element.tag.endswith("circle"):
            try:
                cx = float(element.attrib["cx"])
                cy = float(element.attrib["cy"])
                r = float(element.attrib["r"])
                circles.append((cx, cy, r))
            except Exception:
                continue

    # --- 2 Cairo-style <path> elements (C commands) ---
    if not circles:
        for element in root.iter():
            if element.tag.endswith("path"):
                d = element.attrib.get("d", "")
                try:
                    # Extract numeric values
                    tokens = d.replace("M", " ").replace("C", " ").split()
                    nums = [float(x) for x in tokens if x.replace(".", "", 1).replace("-", "", 1).isdigit()]
                    if len(nums) >= 6:
                        cx, cy = nums[0], nums[1]
                        # Estimate radius from control point distances
                        r_est = abs(nums[0] - nums[2]) or abs(nums[1] - nums[3])
                        if r_est > 0:
                            circles.append((cx, cy, r_est))
                except Exception:
                    continue

    if not circles:
        print("  No <circle> or <path> elements found - skipping this file.")
        return

    # Calculate bounds and normalization parameters
    xs = [c[0] for c in circles]
    ys = [c[1] for c in circles]
    rs = [c[2] for c in circles]

    min_x, max_x = min(xs), max(xs)
    min_y, max_y = min(ys), max(ys)
    r_max = max(rs)

    width = max_x - min_x
    height = max_y - min_y

    # Compute center to normalize all translations
    cx_center = (min_x + max_x) / 2
    cy_center = (min_y + max_y) / 2

    # ================================
    #   GENERATE SCAD OUTPUT CONTENT
    # ================================

    scad_path = SCAD_DIR / f"{svg_file.stem}.scad"
    with open(scad_path, "w", encoding="utf-8") as scad:
        scad.write(f"// Auto-generated from {svg_file.name}\n")
        scad.write("// -------------------------------------------------\n")
        scad.write(f"// H_BASE={H_BASE} mm | H_MAX={H_MAX} mm | GAMMA={GAMMA}\n")
        scad.write("// Generated via svg_to_scad_converter.py\n\n")
        scad.write("union() {\n")

        # Iterate through all detected dots
        for cx, cy, r in circles:
            h = H_BASE + H_MAX * (r / r_max) ** GAMMA
            tx = cx - cx_center
            ty = cy - cy_center
            scad.write(f"  translate([{tx:.3f}, {ty:.3f}, 0]) cylinder(r={r:.3f}, h={h:.3f});\n")

        # Add base plane (optional)
        if EXTRUDE_BASE:
            scad.write(
                f"\n  // Base plate\n"
                f"  translate([{-(width/2):.3f}, {-(height/2):.3f}, 0]) "
                f"cube([{width:.3f}, {height:.3f}, {H_BASE:.3f}]);\n"
            )

        scad.write("}\n")

    print(f"  SCAD file generated: {scad_path.name}")

    # Rename original SVG to mark it as processed
    converted_path = svg_file.with_name(svg_file.stem + "_converted.svg")
    try:
        svg_file.rename(converted_path)
        print(f"  Marked as converted: {converted_path.name}")
    except Exception as e:
        print(f"  Could not rename SVG: {e}")


# ==========================================
# MAIN EXECUTION LOOP
# ==========================================

def main():
    """
    Main control function that scans the SVG directory,
    converts all unprocessed SVGs, and outputs SCAD files.
    """
    print("===============================================")
    print("     HALFTONE SVG -> SCAD 3D CONVERTER v1.0     ")
    print("===============================================\n")

    svg_files = list(SVG_DIR.glob("*.svg"))

    if not svg_files:
        print("No SVG files found in the SVG directory.\n")
        return

    # Process each unconverted SVG file
    for svg_file in svg_files:
        if svg_file.name.endswith("_converted.svg"):
            continue
        convert_svg_to_scad(svg_file)

    print("\nAll available SVG files have been processed.\n")
    print(f"Output SCAD files stored in: {SCAD_DIR.resolve()}")


# ==========================================
# ENTRY POINT
# ==========================================

if __name__ == "__main__":
    main()
